const { execFileSync } = require('child_process')
const path = require('path')
const fs = require('fs')
const initialize = require('./utils/initialize')
const { buildComposeYaml } = require('./utils/compose-yaml')
const { ensureConfigFromExamples, gatewayPackageDir } = require('./utils/service-bootstrap')

// Every file startServices writes into the site dir carries this marker. A
// file without it (or the legacy header) is the user's, and is never
// overwritten unless config.overwrite is set.
const GENERATED_MARKER = '@generated by @tetherto/mdk-core startServices'
const LEGACY_MARKERS = ['Auto-generated by @tetherto/mdk']

function _isGenerated (content) {
  return content.includes(GENERATED_MARKER) || LEGACY_MARKERS.some((m) => content.includes(m))
}

/**
 * Writes `content` (which must already contain GENERATED_MARKER) to `file`,
 * refusing to replace an existing file that was not generated by us — or
 * whose content is not byte-identical to what we would write (`same`).
 */
function writeGenerated (file, content, { overwrite = false, same = null } = {}) {
  if (!overwrite && fs.existsSync(file)) {
    const existing = fs.readFileSync(file, 'utf8')
    if (!_isGenerated(existing) && existing !== same) {
      throw new Error(
        `ERR_MDK_GENERATED_FILE_CONFLICT: ${file} exists and was not generated by @tetherto/mdk-core; ` +
        'move it away or pass overwrite: true'
      )
    }
  }
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, content)
}

// Bind a published port to loopback unless the caller names a host.
function _publishPort (port, host) {
  return `${host || '127.0.0.1'}:${port}:${port}`
}

/**
 * Generates (and optionally starts) a PM2 ecosystem or Docker compose stack
 * in the current working directory.
 *
 * config: { runtime: 'pm2' | 'docker', repoRoot, services, env?, image?, shouldAutoStart?,
 *           repoRoot  the MDK source checkout the services run from (required;
 *                    never searched for). Config is seeded from its example
 *                    files and it is passed to the processes as MDK_REPO_ROOT.
 *           host?    Docker: interface published gateway ports bind to
 *                    (default '127.0.0.1'; per-service `svc.host` wins),
 *           overwrite?  replace site-dir files that were not generated by
 *                    mdk-core (default false: refuse with ERR_MDK_GENERATED_FILE_CONFLICT) }
 */
// The checkout is always named by the caller — never found by walking up
// from the working directory or this package.
function _resolveRepoRoot (config) {
  const root = config.repoRoot
  if (typeof root !== 'string' || !root.trim()) {
    throw new Error('ERR_MDK_REPO_ROOT_REQUIRED: startServices needs config.repoRoot — the MDK source checkout the services run from')
  }
  return path.resolve(root)
}

const startServices = async (config) => {
  if (config.runtime === 'pm2') {
    return startPm2(config)
  }

  if (config.runtime === 'docker') {
    return startDocker(config)
  }

  throw new Error(`Unsupported runtime: ${config.runtime}`)
}

function _copyGenerated (src, dest, opts) {
  const body = fs.readFileSync(src, 'utf8')
  // The marker goes on line 1 (a comment before 'use strict' keeps the
  // directive prologue intact). An unmarked copy identical to the source —
  // what older versions wrote — still counts as ours.
  writeGenerated(dest, `// ${GENERATED_MARKER} — do not edit; rewritten on every run\n${body}`, { ...opts, same: body })
}

function ensureMdkWorker (cwd = process.cwd(), opts = {}) {
  const mdkDir = path.join(cwd, 'mdk')
  const utilsDir = path.join(mdkDir, 'utils')

  _copyGenerated(path.join(__dirname, 'worker.js'), path.join(mdkDir, 'worker.js'), opts)
  _copyGenerated(
    path.join(__dirname, 'utils', 'service-bootstrap.js'),
    path.join(utilsDir, 'service-bootstrap.js'),
    opts
  )

  // Leftovers of the old pm2 bootstrap — removed only when they are ours.
  for (const legacy of [
    path.join(mdkDir, 'pm2-bootstrap.js'),
    path.join(utilsDir, 'pm2-bootstrap.js')
  ]) {
    if (fs.existsSync(legacy) && _isGenerated(fs.readFileSync(legacy, 'utf8'))) fs.unlinkSync(legacy)
  }

  return path.join(mdkDir, 'worker.js')
}

function startPm2 (config) {
  const mdkEnv = config.env || 'development'
  const repoRoot = _resolveRepoRoot(config)
  const writeOpts = { overwrite: config.overwrite === true }

  initialize({ sources: repoRoot })
  ensureMdkWorker(process.cwd(), writeOpts)
  ensureConfigFromExamples(path.join(gatewayPackageDir(), 'config'))

  const workerScript = 'mdk/worker.js'
  const sharedEnv = {
    MDK_ENV: mdkEnv,
    MDK_REPO_ROOT: repoRoot,
    NODE_ENV: mdkEnv === 'production' ? 'production' : 'development'
  }

  const apps = config.services.map(svc => {
    if (svc.kind === 'gateway') {
      return {
        name: `mdk-${svc.name}`,
        script: workerScript,
        cwd: process.cwd(),
        exec_mode: 'fork',
        instances: 1,
        env: {
          ...sharedEnv,
          SERVICE: 'gateway',
          PORT: String(svc.port)
        }
      }
    }

    return {
      name: `mdk-${svc.name}`,
      script: workerScript,
      cwd: process.cwd(),
      exec_mode: 'fork',
      instances: 1,
      env: {
        ...sharedEnv,
        SERVICE: 'worker',
        WORKER: svc.worker,
        TYPE: svc.type,
        RACK: svc.rack
      }
    }
  })

  // PM2 only treats filenames containing .config.js (or .json/.yaml) as ecosystem files.
  const file = path.join(process.cwd(), 'ecosystem.config.js')
  const content = `// ${GENERATED_MARKER} — do not edit manually
module.exports = ${JSON.stringify({ apps }, null, 2)}
`

  writeGenerated(file, content, writeOpts)
  if (config.shouldAutoStart) {
    execFileSync('pm2', ['start', file], { stdio: 'inherit' })
  }
}

function startDocker (config) {
  if (!config.image) {
    throw new Error('Docker runtime requires "image"')
  }

  const mdkEnv = config.env || 'development'
  const siteDir = process.cwd()
  const repoRoot = _resolveRepoRoot(config)
  const repoMount = path.relative(siteDir, repoRoot).split(path.sep).join('/') || '.'

  const writeOpts = { overwrite: config.overwrite === true }

  initialize({ sources: repoRoot })
  ensureMdkWorker(siteDir, writeOpts)
  ensureConfigFromExamples(path.join(gatewayPackageDir(), 'config'))

  const siteMount = path.relative(repoRoot, siteDir).split(path.sep).join('/') || '.'
  const workingDir = `/app/repo/${siteMount}`
  const entrypoint = path.posix.join('/app/repo', siteMount, 'docker-entrypoint.sh')

  const sharedEnv = {
    MDK_ENV: mdkEnv,
    MDK_REPO_ROOT: '/app/repo',
    NODE_ENV: mdkEnv === 'production' ? 'production' : 'development'
  }

  const services = {}

  for (const svc of config.services) {
    const base = {
      image: config.image,
      working_dir: workingDir,
      entrypoint: ['sh', entrypoint],
      restart: 'unless-stopped',
      volumes: [`${repoMount}:/app/repo:cached`],
      environment: { ...sharedEnv }
    }

    if (svc.kind === 'gateway') {
      services[svc.name] = {
        ...base,
        environment: {
          ...base.environment,
          SERVICE: 'gateway',
          PORT: String(svc.port)
        },
        // Loopback unless an interface is explicitly configured.
        ports: [_publishPort(svc.port, svc.host || config.host)]
      }
      continue
    }

    services[svc.name] = {
      ...base,
      environment: {
        ...base.environment,
        SERVICE: 'worker',
        WORKER: svc.worker,
        TYPE: svc.type,
        RACK: svc.rack
      }
    }
  }

  const compose = {
    version: '3.8',
    services
  }

  const file = path.join(siteDir, 'docker-compose.generated.yml')
  writeGenerated(file, `# ${GENERATED_MARKER} — do not edit manually\n${buildComposeYaml(compose)}`, writeOpts)

  if (config.shouldAutoStart) {
    execFileSync('docker', ['compose', '-f', file, 'up', '-d'], { stdio: 'inherit', cwd: siteDir })
  }

  return { file, repoRoot, siteDir }
}

module.exports = { startServices, GENERATED_MARKER }
